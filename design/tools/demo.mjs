// Builds the clickable demo (design/demo/) from the design pages 01 to 16 (Phases 1 to 4).
// Each page is copied as-is, with the mockup harness (mockup.js, the State/Width bar) swapped for the
// demo harness (demo/demo.js + demo/demo.css): links open in the same tab, the demo session tracks who's
// logged in, and a floating Demo panel jumps to any state. The source pages are never changed.
//
// Usage:
//   node design/tools/demo.mjs                    regenerate design/demo/NN-*.html after a page changes
//   node design/tools/demo.mjs --publish <outDir> also write a flat, self-contained copy for publishing
//                                                 (styles and scripts inlined, images beside the pages)
//     --start walkthrough.html                    publish the presenter walkthrough instead of the free demo
//                                                 (start screen walkthrough.html, plus guide.html)
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const pagesDir = path.join(root, 'pages');
const demoDir = path.join(root, 'demo');
// Coach-side states left out of the demo (keep in step with HIDDEN in demo/demo.js).
const HIDDEN = {
  '02': ['own', 'preview'],
  '06': ['coach-upcoming', 'coach-cancel', 'coach-request-received', 'coach-pending', 'coach-completed', 'coach-dispute'],
  '07': ['coach-after', 'coach-payment', 'respond', 'response-sent'],
  '08': ['coach-waiting', 'coach-ended'],
};

const pages = fs.readdirSync(pagesDir).filter((f) => /^(0[1-9]|1[0-6])-.+\.html$/.test(f)).sort();
const counts = {};
for (const file of pages) {
  const num = file.slice(0, 2);
  let html = fs.readFileSync(path.join(pagesDir, file), 'utf8');
  const states = [...html.matchAll(/<section data-state="([^"]+)"/g)].map((m) => m[1]);
  counts[num] = states.filter((s) => !(HIDDEN[num] || []).includes(s)).length;

  const swaps = [
    [/<title>\d\d ([^<]+)<\/title>/, (m, name) => `<title>${name} · Harbourly demo</title>`],
    ['<link rel="stylesheet" href="../foundations/mockup.css">', '<link rel="stylesheet" href="../foundations/mockup.css">\n<link rel="stylesheet" href="demo.css">'],
    ['<script src="../foundations/mockup.js"></script>', '<script src="demo.js"></script>\n<script src="tour.js"></script>'],
    ['<!doctype html>', `<!doctype html>\n<!-- Generated by design/tools/demo.mjs from design/pages/${file}. Edit that page, then run: node design/tools/demo.mjs -->`],
  ];
  for (const [from, to] of swaps) {
    const before = html;
    html = html.replace(from, to);
    if (html === before) throw new Error(`${file}: expected to find ${from}`);
  }
  fs.writeFileSync(path.join(demoDir, file), html);
}

// State counts on the start screen.
const indexPath = path.join(demoDir, 'index.html');
let index = fs.readFileSync(indexPath, 'utf8');
index = index.replace(/(<span class="c" data-count="(\d\d)">)[^<]*(<\/span>)/g, (m, open, num, close) => `${open}${counts[num] ?? ''}${close}`);
fs.writeFileSync(indexPath, index);
console.log(`demo: ${pages.length} pages, ${Object.values(counts).reduce((a, b) => a + b, 0)} states → ${path.relative(process.cwd(), demoDir)}`);

// --publish <outDir>: flat copy. The start screen is published as the artifact's page (index.html, without its
// own document skeleton) and again as start.html, which the other pages link back to.
const pi = process.argv.indexOf('--publish');
if (pi > -1) {
  const outDir = path.resolve(process.argv[pi + 1]);
  const si = process.argv.indexOf('--start');
  const startFile = si > -1 ? process.argv[si + 1] : 'index.html';
  const extras = startFile === 'walkthrough.html' ? ['guide.html'] : [];
  fs.rmSync(outDir, { recursive: true, force: true });
  fs.mkdirSync(outDir, { recursive: true });
  const isLocal = (u) => !/^(https?:|data:|#)/.test(u);
  const assets = new Set();
  const flatten = (file) => {
    const dir = demoDir;
    let html = fs.readFileSync(path.join(dir, file), 'utf8');
    html = html.replace(/<link rel="stylesheet" href="([^"]+)">/g, (m, href) =>
      isLocal(href) ? `<style>/* ${path.basename(href)} */\n${fs.readFileSync(path.resolve(dir, href), 'utf8')}</style>` : m);
    html = html.replace(/<script src="([^"]+)"><\/script>/g, (m, src) => {
      if (!isLocal(src)) return m;
      let js = fs.readFileSync(path.resolve(dir, src), 'utf8');
      if (src === 'demo.js') js = js.replace("var START = 'index.html';", "var START = 'start.html';");
      if (src === 'tour.js') js = js.replace("var WT = 'walkthrough.html';", `var WT = '${startFile === 'walkthrough.html' ? 'start.html' : 'walkthrough.html'}';`);
      return `<script>/* ${path.basename(src)} */\n${js}</script>`;
    });
    html = html.replace(/src="([^"]+\.(?:png|jpe?g|webp|svg))"/g, (m, src) => {
      if (!isLocal(src)) return m;
      const abs = path.resolve(dir, src);
      assets.add(abs);
      return `src="${path.basename(abs)}"`;
    });
    html = html.split(`href="${startFile}"`).join('href="start.html"');
    return html.replace(/<!-- Generated by[^>]*-->\n?/, '');
  };
  for (const file of pages.concat(extras)) fs.writeFileSync(path.join(outDir, file), flatten(file));
  const start = flatten(startFile);
  fs.writeFileSync(path.join(outDir, 'start.html'), start);
  // The artifact page itself: drop the document skeleton (the publisher adds one), keep title, styles and body.
  const head = start.match(/<head>([\s\S]*?)<\/head>/)[1].replace(/<meta charset[^>]*>\n?|<meta name="viewport"[^>]*>\n?/g, '');
  const body = start.match(/<body>([\s\S]*?)<\/body>/)[1];
  const tourAttr = start.match(/<html[^>]*data-tour="([^"]+)"/);
  const keepAttr = tourAttr ? `<script>document.documentElement.setAttribute('data-tour', '${tourAttr[1]}');</script>\n` : '';
  fs.writeFileSync(path.join(outDir, 'index.html'), `${head.trim()}\n<meta name="claude:viewport-fit-sides" content="cover">\n${keepAttr}${body.trim()}\n`);
  for (const a of assets) fs.copyFileSync(a, path.join(outDir, path.basename(a)));
  console.log(`publish (${startFile}): ${pages.length + extras.length + 2} pages and ${assets.size} images → ${outDir}`);
}
